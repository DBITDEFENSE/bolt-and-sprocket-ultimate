"""Builds gravelight/ui/wordmark/claude_zombies.svg: CLAUDE ZOMBIES wordmark (UPDATE 09 section 6, T-140).
Lettering = Stardos Stencil Bold (OFL, assets/third_party/google_fonts/stardos-stencil) converted to outlines with
fontTools, so the SVG needs no font at render time. Run (needs fontTools): python tools/gen_wordmark_svg.py
Look: CLAUDE small and letter-spaced over ZOMBIES large; violet (#c07dff) Nachtglas glow (stacked soft strokes,
no filters, so Godot's SVG rasteriser draws it) with amber cracks; a tally (four strokes + the fifth crossing)
between two rules under the word."""
import random
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "assets/third_party/google_fonts/stardos-stencil/StardosStencil-Bold.ttf"
OUT = ROOT / "gravelight/ui/wordmark/claude_zombies.svg"
W, H = 2048, 940
VIOLET, VIOLET_LIGHT, AMBER = "#c07dff", "#ecdcff", "#ffb23e"


def word(font, text, size, tracking, x_center, baseline):
    """Returns (path_d, x0, x1, top, bottom) for text drawn at size px with extra tracking px."""
    gs, cmap, upm = font.getGlyphSet(), font.getBestCmap(), font["head"].unitsPerEm
    sc = size / upm
    adv = [gs[cmap[ord(c)]].width * sc for c in text]
    total = sum(adv) + tracking * (len(text) - 1)
    x = x_center - total / 2
    x0 = x
    d = []
    for c, a in zip(text, adv):
        pen = SVGPathPen(gs)
        gs[cmap[ord(c)]].draw(TransformPen(pen, (sc, 0, 0, -sc, x, baseline)))
        d.append(pen.getCommands())
        x += a + tracking
    return " ".join(d), x0, x0 + total, baseline - size * 0.72, baseline


def main():
    font = TTFont(str(FONT))
    cz, cx0, cx1, ct, cb = word(font, "CLAUDE", 150, 62, W / 2, 205)
    zz, zx0, zx1, zt, zb = word(font, "ZOMBIES", 400, 8, W / 2, 690)
    rnd = random.Random(1944)
    cracks = []
    for i in range(7):   # jagged amber cracks across the big letters
        x = zx0 + (zx1 - zx0) * (i + 0.5) / 7 + rnd.uniform(-30, 30)
        y = zt + rnd.uniform(0, 40)
        pts = [(x, y)]
        while y < zb - 20:
            y += rnd.uniform(36, 70)
            x += rnd.uniform(-34, 34)
            pts.append((x, y))
        cracks.append("M" + " L".join("%.0f %.0f" % p for p in pts))
    for i in range(3):   # and a few through CLAUDE
        x = cx0 + (cx1 - cx0) * (i * 2 + 1) / 7
        y = ct + 4
        pts = [(x, y)]
        while y < cb - 14:
            y += rnd.uniform(18, 30)
            x += rnd.uniform(-12, 12)
            pts.append((x, y))
        cracks.append("M" + " L".join("%.0f %.0f" % p for p in pts))
    crack_d = " ".join(cracks)
    # tally under the word: four strokes and the fifth across them, between two rules
    ty0, ty1 = 800, 905
    tx = W / 2 - 100
    tally = " ".join("M%.0f %d L%.0f %d" % (tx + i * 50 + rnd.uniform(-2, 2), ty0, tx + i * 50 + rnd.uniform(-3, 3), ty1) for i in range(4))
    tally += " M%.0f %d L%.0f %d" % (tx - 34, ty1 - 14, tx + 3 * 50 + 34, ty0 + 14)
    rules = "M%d 852 L%d 852 M%d 852 L%d 852" % (zx0, W / 2 - 190, W / 2 + 190, zx1)
    glow = "".join('<path d="%s" fill="none" stroke="%s" stroke-width="%d" stroke-opacity="%.2f" stroke-linejoin="round"/>' % (cz + " " + zz, VIOLET, sw, op)
                   for sw, op in ((44, 0.025), (32, 0.04), (22, 0.06), (14, 0.09), (7, 0.15)))
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="{W}" height="{H}" viewBox="0 0 {W} {H}">
<!-- CLAUDE ZOMBIES wordmark. Original lettering: Stardos Stencil Bold (SIL OFL 1.1) outlines. Generated by tools/gen_wordmark_svg.py -->
<defs>
<path id="w" d="{cz} {zz}"/>
<linearGradient id="fill" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{VIOLET_LIGHT}"/><stop offset="0.55" stop-color="{VIOLET}"/><stop offset="1" stop-color="#6c3fb0"/></linearGradient>
<clipPath id="clip"><use href="#w"/></clipPath>
</defs>
<g id="glow">{glow}</g>
<use href="#w" fill="url(#fill)" stroke="#12081f" stroke-width="5" stroke-linejoin="round"/>
<g clip-path="url(#clip)"><path d="{crack_d}" fill="none" stroke="{AMBER}" stroke-width="5" stroke-linejoin="miter" stroke-linecap="round"/></g>
<path d="{rules}" stroke="{VIOLET}" stroke-opacity="0.7" stroke-width="4" fill="none"/>
<path d="{tally}" stroke="#12081f" stroke-width="20" stroke-linecap="round" fill="none"/>
<path d="{tally}" stroke="{AMBER}" stroke-width="11" stroke-linecap="round" fill="none"/>
</svg>
'''
    OUT.write_text(svg, encoding="utf-8")
    print("wrote", OUT, len(svg), "bytes")


def icon():
    """claude_zombies_icon.svg: the Z with the tally on a dark tile (512 units; the renderer scales to 256 px)."""
    font = TTFont(str(FONT))
    z, x0, x1, top, bot = word(font, "Z", 400, 0, 256, 390)
    glow = "".join('<path d="%s" fill="none" stroke="%s" stroke-width="%d" opacity="%.2f" stroke-linejoin="round"/>' % (z, VIOLET, sw, op)
                   for sw, op in ((34, 0.03), (24, 0.05), (15, 0.09), (8, 0.16)))
    tx = 256 - 75
    tally = " ".join("M%d 430 L%d 484" % (tx + i * 50, tx + i * 50) for i in range(4)) + " M%d 474 L%d 440" % (tx - 22, tx + 172)
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="512" height="512" viewBox="0 0 512 512">
<defs><linearGradient id="f" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{VIOLET_LIGHT}"/><stop offset="0.6" stop-color="{VIOLET}"/><stop offset="1" stop-color="#6c3fb0"/></linearGradient></defs>
<rect width="512" height="512" rx="72" fill="#12081f"/>
<g id="glow">{glow}</g>
<path d="{z}" fill="url(#f)" stroke="#12081f" stroke-width="4"/>
<path d="M200 130 L228 190 L212 240 L246 300" fill="none" stroke="{AMBER}" stroke-width="5" stroke-linecap="round"/>
<path d="{tally}" stroke="{AMBER}" stroke-width="10" stroke-linecap="round" fill="none"/>
</svg>
'''
    (OUT.parent / "claude_zombies_icon.svg").write_text(svg, encoding="utf-8")


main()
icon()
