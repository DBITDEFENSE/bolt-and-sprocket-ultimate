"""Builds data/gravelight/perk_lore.json from docs/JINGLES.md (the master file for the Helvetia machines):
per perk: plan name + ID (the stencil), the human behind the formula (title + story), and the fine-print
panel on the back (BBCode lines). Re-run after editing JINGLES.md.
Also builds data/gravelight/machine_lore.json from docs/gravelight/PERKS_LORE.md sections 4+ (T-075): per built map,
why each perk machine, the Crucible and the wall guns are where they are (plate line, Archive title and text).
Usage: python tools/build_perk_lore.py"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "JINGLES.md")
OUT = os.path.join(ROOT, "data", "gravelight", "perk_lore.json")

head_re = re.compile(r"^## \d+\. (.+?) \(`([a-z_]+)`\)")
plan_re = re.compile(r"^\| \*\*Plan\*\* \| \*\*(.+?)\*\* · `(DMS-VP-[A-Z0-9-]+)` \|")
human_re = re.compile(r"^\*\*The human: (.+?)\*\*(?: \*\(.*?\)\*)?\.?\s*(.*)$")


def bb(md: str) -> str:
    md = re.sub(r"\*\*(.+?)\*\*", r"[b]\1[/b]", md)
    md = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"[i]\1[/i]", md)
    return md.replace("`", "")


def main() -> None:
    lines = open(SRC, encoding="utf-8").read().splitlines()
    out = {}
    cur = None
    in_panel = False
    for ln in lines:
        m = head_re.match(ln)
        if m:
            cur = {"name": m.group(1), "plan_name": "", "plan_id": "", "human": "", "human_story": "", "panel": []}
            out[m.group(2)] = cur
            in_panel = False
            continue
        if cur is None:
            continue
        if ln.startswith("## "):
            cur = None
            continue
        pm = plan_re.match(ln)
        if pm:
            cur["plan_name"], cur["plan_id"] = pm.group(1), pm.group(2)
        hm = human_re.match(ln)
        if hm and not cur["human"]:
            cur["human"] = hm.group(1)
            cur["human_story"] = bb(hm.group(2).strip())
        if ln.strip().startswith("`panel."):
            in_panel = True
            continue
        if in_panel:
            if ln.startswith(">"):
                cur["panel"].append(bb(ln[1:].strip()))
            elif ln.strip() == "---" or (ln.strip() and not ln.startswith(">")):
                in_panel = False
    for k, v in out.items():
        while v["panel"] and v["panel"][-1] == "":
            v["panel"].pop()
        missing = [f for f in ("plan_id", "human", "panel") if not v[f]]
        if missing:
            print("WARN %s missing %s" % (k, missing))
    doc = {"_doc": "Generated by tools/build_perk_lore.py from docs/JINGLES.md. Plan IDs (stencils, section 0.2), "
                   "the human behind each formula (section 10.2 / 11.3), and the fine-print panels (section 0.3).",
           "perks": out}
    json.dump(doc, open(OUT, "w", encoding="utf-8", newline="\n"), indent=1, ensure_ascii=False)
    print("wrote %d perks -> %s" % (len(out), os.path.relpath(OUT, ROOT)))


# ------------------------------------------------------------------ machine_lore.json (T-075)

MSRC = os.path.join(ROOT, "docs", "gravelight", "PERKS_LORE.md")
MOUT = os.path.join(ROOT, "data", "gravelight", "machine_lore.json")
map_head_re = re.compile(r"^## \d+\. (.+?) \(`([a-z0-9_]+)`\)\s*$")
entry_re = re.compile(r"^### ([a-z0-9_.]+)\s*$")


def build_machine_lore() -> None:
    """PERKS_LORE.md: '## N. Name (`map_id`)' opens a map, '**Archive map:** x' sets its Archive group, each
    '### key' (perk.<id>, crucible, chalk, chalk.<weapon>) is an entry with '**Plate:**', '**Archive:**' and
    paragraphs of text. Everything else (the design sections, HTML comments) is ignored."""
    maps = {}
    cur_map = None
    cur = None
    para = []
    in_comment = False

    def flush_para():
        if cur is not None and para:
            cur["paras"].append(" ".join(para).strip())
        para.clear()

    for ln in open(MSRC, encoding="utf-8").read().splitlines():
        st = ln.strip()
        if in_comment or st.startswith("<!--"):
            in_comment = not st.endswith("-->")
            continue
        mh = map_head_re.match(ln)
        if mh:
            flush_para()
            cur = None
            cur_map = {"name": mh.group(1), "archive_map": "", "entries": {}}
            maps[mh.group(2)] = cur_map
            continue
        if ln.startswith("## "):
            flush_para()
            cur = None
            cur_map = None
            continue
        if cur_map is None:
            continue
        if st.startswith("**Archive map:**"):
            cur_map["archive_map"] = st.split("**Archive map:**", 1)[1].strip()
            continue
        me = entry_re.match(ln)
        if me:
            flush_para()
            cur = {"plate": "", "title": "", "paras": []}
            cur_map["entries"][me.group(1)] = cur
            continue
        if cur is None:
            continue
        if st.startswith("**Plate:**"):
            cur["plate"] = st.split("**Plate:**", 1)[1].strip()
        elif st.startswith("**Archive:**"):
            cur["title"] = st.split("**Archive:**", 1)[1].strip()
        elif st == "" or st == "---":
            flush_para()
        else:
            para.append(st)
    flush_para()
    out = {}
    for mid, m in maps.items():
        ents = {}
        for k, e in m["entries"].items():
            row = {"plate": e["plate"]}
            if e["title"]:
                row["title"] = e["title"]
            if e["paras"]:
                row["text"] = "\n\n".join(e["paras"])
            if not e["plate"] and not e["paras"]:
                print("WARN %s %s is empty" % (mid, k))
            ents[k] = row
        out[mid] = {"name": m["name"], "archive_map": m["archive_map"] or mid, "entries": ents}
    doc = {"_doc": "Generated by tools/build_perk_lore.py from docs/gravelight/PERKS_LORE.md sections 4+ (DECISIONS T-075). Per built "
                   "map: entries keyed perk.<perk_id> (the maker's plate), crucible (its brass plate), chalk (the map's chalk "
                   "entry) and chalk.<weapon_id> (the line under a wall gun's prompt). plate = the one-line text; title + text = "
                   "the Intel Archive row (the text's first paragraph is the reader's caption). Read by gravelight/world/machine_lore.gd.",
           "maps": out}
    json.dump(doc, open(MOUT, "w", encoding="utf-8", newline="\n"), indent=1, ensure_ascii=False)
    print("wrote %d maps, %d entries -> %s" % (len(out), sum(len(m["entries"]) for m in out.values()), os.path.relpath(MOUT, ROOT)))


if __name__ == "__main__":
    main()
    build_machine_lore()
