#!/usr/bin/env python3
"""UPDATE 12 section 2 (DECISIONS T-208): files the material audit.

gravelight/tools_src/material_audit.gd writes <dir>/<map_id>.json per map (tools/look/material_audit.sh runs it).
This merges them:
  --report docs/look/material_audit.md   the per-map table (materials, checked, exempt, skipped; every issue before
                                         and after the pass), the exempt and skipped materials by reason, and every
                                         remaining outlier with why it stays;
  --write-fixes data/look/_materials.json  merges the texture fixes the run found (`tex_tint`, `tex_rough`) into the
                                         pass's data (existing entries kept unless the run found a different value).
Pure file work: no Godot here.

    python -I tools/look/material_audit.py .smoke_logs/material_audit --report docs/look/material_audit.md
"""
import argparse
import json
import os
import sys

ISSUES = ["rough_low", "clean_plastic", "albedo_sat", "albedo_value", "no_wear"]
ORDER = ["map00_crossroads", "map01_kaltenbrunn", "map02_totenhafen", "map04a_thalbach", "map04b_kranich",
         "map04c_groomlake", "map04d_mondlicht"]
# Why an outlier that the pass leaves is allowed to stay (keyed by a word in its texture / node / material name).
REASONS = {}


def load(d: str) -> list:
    out = []
    for fn in os.listdir(d):
        if fn.endswith(".json"):
            with open(os.path.join(d, fn), encoding="utf-8") as f:
                out.append(json.load(f))
    out.sort(key=lambda r: ORDER.index(r["map"]) if r["map"] in ORDER else 99)
    return out


def write_fixes(reports: list, data_path: str) -> None:
    with open(data_path, encoding="utf-8") as f:
        data = json.load(f)
    n = 0
    for k in ("tex_tint", "tex_rough"):
        cur = data.get(k, {})
        for r in reports:
            for key, val in sorted(r.get("fixes", {}).get(k, {}).items()):
                if key.startswith("id:"):
                    continue
                if cur.get(key) != val:
                    cur[key] = val
                    n += 1
        data[k] = dict(sorted(cur.items()))
    with open(data_path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(f"{data_path}: {n} texture fixes written ({len(data['tex_tint'])} tints, {len(data['tex_rough'])} roughness)")


def reason_for(item: dict) -> str:
    s = " ".join(str(item.get(k, "")) for k in ("texture", "node", "name")).lower()
    for w, why in REASONS.items():
        if w in s:
            return why
    return "(open)"


def report(reports: list, out: str) -> None:
    lines = ["# Material audit (UPDATE 12 section 2, DECISIONS T-208)", "",
             "Generated by `tools/look/material_audit.sh` (gravelight/tools_src/material_audit.gd, the rules in",
             "data/look/_materials.json, docs/ART_BIBLE.md section 7). Every material on every map, once; *before* is the",
             "map as built, *after* is with the material pass (LookMaterials, applied when the map loads).", "",
             "| Map | Materials | Checked | Exempt | Skipped | " + " | ".join(f"{i} before / after" for i in ISSUES) + " | Total before / after |",
             "|---|---|---|---|---|" + "---|" * (len(ISSUES) + 1)]
    tb = ta = 0
    for r in reports:
        b, a = r["before"], r["after"]
        cells = [f"{b.get(i, 0)} / {a.get(i, 0)}" for i in ISSUES]
        tb += r["before_total"]
        ta += r["after_total"]
        lines.append(f"| {r['map']} | {r['materials']} | {r['checked']} | {r['exempt']} | {r['skipped']} | " + " | ".join(cells)
                     + f" | **{r['before_total']} / {r['after_total']}** |")
    lines += ["", f"All maps: **{tb} outliers before, {ta} after.**", "",
              "## Exempt (outside the rules by design) and skipped (another pass owns them)", ""]
    for r in reports:
        ex = ", ".join(f"{k} {v}" for k, v in sorted(r.get("exempt_by", {}).items()))
        sk = ", ".join(f"{k} {v}" for k, v in sorted(r.get("skipped_by", {}).items()))
        lines.append(f"- **{r['map']}**: exempt: {ex or 'none'}; skipped: {sk or 'none'}")
    lines += ["", "Exempt: transparent and unshaded materials (glass, fog cards, impostors, beams), emissive ones (lamps,",
              "fire, Nachtglas), and every shader other than the shared surface shader (the snow, salt, water, sky, foliage",
              "and weapon shaders own their surfaces). Skipped: characters (rigged: the infection shader and the skin rules),",
              "players' viewmodels and mounted guns (gun-metal rules, docs/WEAPON_MODELS.md), section 5's C-47 wreck (its own",
              "art pass) and the cartoon worlds (Bolt & Sprocket, The Fine Print stay cartoon).", "",
              "## Remaining outliers", ""]
    any_left = False
    for r in reports:
        for item in r.get("remaining", []):
            any_left = True
            lines.append(f"- {r['map']}: {', '.join(item['issues'])} on `{item.get('name') or item['class']}` "
                         f"({item.get('node', '')}; albedo {item.get('albedo')} s {item.get('sat')} v {item.get('val')}, "
                         f"roughness {item.get('roughness')}, texture `{item.get('texture') or '-'}`): {reason_for(item)}")
    if not any_left:
        lines.append("None: the audit is clean.")
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{out}: {len(reports)} maps, {tb} outliers before, {ta} after")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("dir")
    ap.add_argument("--report")
    ap.add_argument("--write-fixes")
    a = ap.parse_args()
    reports = load(a.dir)
    if not reports:
        print("no audit json in " + a.dir)
        return 1
    if a.write_fixes:
        write_fixes(reports, a.write_fixes)
    if a.report:
        report(reports, a.report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
