"""Builds docs/FINEPRINT_SCRIPT.md (the full Fine Print script) from the per-chapter sources in
docs/fineprint/script_ch1..5.md. Edit the chapter files, then re-run: python tools/build_fineprint_script.py"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CH = [("1", "SYNERGY SCREENING"), ("2", "FIELD UNIT"), ("3", "HELVETIA AUTOMATEN AG"), ("4", "PATENT PENDING"), ("5", "RETURN POLICY")]
parts = []
counts = []
for n, title in CH:
    src = os.path.join(ROOT, "docs", "fineprint", "script_ch%s.md" % n)
    text = open(src, encoding="utf-8").read().strip()
    ids = set(re.findall(r"`(fp\.c%s\.[a-z0-9_]+\.\d+)`" % n, text))
    counts.append((n, title, len(ids)))
    parts.append("\n\n---\n\n<!-- source: docs/fineprint/script_ch%s.md -->\n\n" % n + text)
head = ["# THE FINE PRINT: Full Script", "",
        "*Generated by `tools/build_fineprint_script.py` from `docs/fineprint/script_ch1..5.md`. Edit the chapter files, not this one.*", "",
        "Bible: `FINEPRINT_LORE.md`. Jingles and back-panel texts: `JINGLES.md`. Crossover map mechanics: `gravelight/MAPS.md` and `gravelight/EASTER_EGGS.md`.", "",
        "| Ch. | Title | Line IDs |", "|---|---|---|"]
for n, t, c in counts:
    head.append("| %s | %s | %d |" % (n, t, c))
head.append("| | **Total** | **%d** |" % sum(c for _, _, c in counts))
open(os.path.join(ROOT, "docs", "FINEPRINT_SCRIPT.md"), "w", encoding="utf-8", newline="\n").write("\n".join(head) + "".join(parts) + "\n")
print("FINEPRINT_SCRIPT.md:", ", ".join("ch%s %d" % (n, c) for n, _, c in counts), "total", sum(c for _, _, c in counts))
