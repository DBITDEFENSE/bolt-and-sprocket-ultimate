#!/usr/bin/env python3
"""Tests for tools/cinema/archive_reel.py (UPDATE 12 s3, T-209). Standard library unittest; needs ffmpeg for the
render tests (they skip without it). Run from anywhere:

    python -I tools/cinema/test_archive_reel.py [-v]

The renders run at a small size (320x180, web 160x90) on synthetic clips made with ffmpeg's testsrc2, placed in a
temp folder (never the owner's assets/user_supplied/cutscenes): the same input must give byte-identical .ogv files on
a second render (the shot build and the whole reel), the build is incremental, and the outputs are Theora (+ Vorbis
for the reel) at the right sizes and lengths. With --keep DIR the generated clips are left in DIR/raw and the built
.ogv in DIR/built (the Godot smoke smoke_cinema_reels can then play them: --reel-root=DIR/built).
"""
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import archive_reel as ar  # noqa: E402

SIZE = "320x180"
WEB = "160x90"
KEEP = None


def sha1(path):
    with open(path, "rb") as f:
        return hashlib.sha1(f.read()).hexdigest()


def probe(path):
    out = subprocess.run([ar.ffprobe(), "-v", "error", "-show_entries", "stream=codec_name,width,height:format=duration",
                          "-of", "json", path], capture_output=True, text=True).stdout
    return json.loads(out or "{}")


def decode_errors(path):
    """Every line the local ffmpeg prints decoding the whole file (empty = a clean Theora stream)."""
    r = subprocess.run([ar.ffmpeg(), "-v", "error", "-nostdin", "-i", path, "-f", "null", "-"], capture_output=True, text=True)
    return r.stderr.strip()


def make_clip(path, seconds, pattern="testsrc2", size="640x360"):
    subprocess.run([ar.ffmpeg(), "-v", "error", "-nostdin", "-y", "-f", "lavfi", "-i",
                    "%s=size=%s:rate=24:duration=%.2f" % (pattern, size, seconds), "-c:v", "libx264", "-pix_fmt", "yuv420p",
                    "-threads", "1", path], check=True)


def make_synthetic_raw(raw, scene="staub", shots=(1, 2, 8)):
    """Synthetic clips for some of a scene's shots: shot 1 longer than its span (trimmed), shot 2 shorter (stretched
    and held with the push), shot 8 the scene's own length."""
    d = os.path.join(raw, scene)
    os.makedirs(d, exist_ok=True)
    spans = {int(s["n"]): s["span"][1] - s["span"][0] for s in ar.reels()["scenes"][scene]["shots"]}
    lens = {1: spans[1] + 2.0, 2: spans[2] * 0.5, 8: spans[8]}
    for n in shots:
        make_clip(os.path.join(d, "shot_%02d.mp4" % n), lens.get(n, spans[n]), "testsrc2" if n % 2 else "testsrc")
    with open(os.path.join(d, "SOURCE.txt"), "w", encoding="utf-8") as f:
        f.write("Title: synthetic test clips\nAuthor: ffmpeg testsrc2\nSource: generated by test_archive_reel.py\n"
                "License: Ours (generated test pattern)\nCredit line: none\n")
    with open(os.path.join(d, "LICENSE.txt"), "w", encoding="utf-8") as f:
        f.write("Generated test patterns; not shipped.\n")
    return d


class PureTests(unittest.TestCase):
    def test_seed_is_stable(self):
        self.assertEqual(ar.seed_of("staub", 3), ar.seed_of("staub", 3))
        self.assertNotEqual(ar.seed_of("staub", 3), ar.seed_of("staub", 4))

    def test_lut_is_monotone_and_in_range(self):
        t = ar.treatment()
        src = [0] * 40 + [5000] * 100 + [0] * 116
        lut = ar.match_lut(src, ar.target_hist(), t)
        self.assertEqual(len(lut), 256)
        self.assertTrue(all(0.0 <= v <= 1.0 for v in lut))
        self.assertTrue(all(lut[i] >= lut[i - 1] for i in range(1, 256)))

    def test_conform_trims_stretches_and_holds(self):
        t = ar.treatment()
        f, k, held = ar.conform(12.0, 8.0, t, 320, 180, 24)
        self.assertEqual(k, 1.0)
        self.assertEqual(held, 0.0)
        f, k, held = ar.conform(7.0, 8.0, t, 320, 180, 24)
        self.assertAlmostEqual(k, 8.0 / 7.0, places=4)
        self.assertEqual(held, 0.0)
        f, k, held = ar.conform(4.0, 10.0, t, 320, 180, 24)
        self.assertAlmostEqual(k, 1.5)
        self.assertAlmostEqual(held, 4.0, places=4)
        self.assertTrue(any(x.startswith("zoompan") for x in f), "a long hold pushes in")

    def test_damage_is_deterministic(self):
        t = ar.treatment()
        a = ar.damage(12345, 6.0, t, 1484, 1080, 24)
        b = ar.damage(12345, 6.0, t, 1484, 1080, 24)
        c = ar.damage(54321, 6.0, t, 1484, 1080, 24)
        self.assertEqual(a, b)
        self.assertNotEqual(a, c)
        self.assertGreater(len(a), 5)

    def test_segments_cover_each_timeline(self):
        cuts = ar.load_json(ar.CUTS_JSON)["cutscenes"]
        for scene in ar.reels()["scenes"]:
            segs = ar.segments(scene)
            self.assertAlmostEqual(segs[0][0], 0.0)
            self.assertAlmostEqual(segs[-1][1], float(cuts[scene]["seconds"]))
            for a, b in zip(segs, segs[1:]):
                self.assertAlmostEqual(a[1], b[0], places=4, msg="%s: a gap or overlap at %.2f" % (scene, a[1]))
            kinds = [s[2] for s in segs]
            self.assertEqual(kinds.count("shot"), len(ar.reels()["scenes"][scene]["shots"]))
            self.assertGreater(kinds.count("card"), 0)

    def test_cards_keep_the_in_engine_english(self):
        cuts = ar.load_json(ar.CUTS_JSON)["cutscenes"]
        native, en = ar.card_texts("lazarus_saturday", 0, cuts["lazarus_saturday"]["shots"][0])
        self.assertEqual(en[0], "CHETVERODNEVO")
        self.assertTrue(any("Ѐ" <= ch <= "ӿ" for ch in native[0]), "the native title is Cyrillic")
        native, en = ar.card_texts("staub", 0, cuts["staub"]["shots"][0])
        self.assertEqual(native[0], "KALTENBRUNN")

    def test_prompts_file_is_current(self):
        with open(ar.PROMPTS_MD, "r", encoding="utf-8") as f:
            self.assertEqual(f.read(), ar.render_prompts(), "run: python -I tools/cinema/archive_reel.py prompts")

    def test_every_prompt_starts_with_the_style_block(self):
        data = ar.reels()
        for scene, sc in data["scenes"].items():
            for s in sc["shots"]:
                self.assertTrue(ar.full_prompt(s, data).startswith(data["style_block"] + ". "))
                self.assertTrue(4 <= int(s["seconds"]) <= 10, "%s shot %d: 4-10 s" % (scene, s["n"]))


@unittest.skipUnless(ar.have_ffmpeg(), "no ffmpeg")
class RenderTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.mkdtemp(prefix="test_archive_reel_")
        cls.raw = os.path.join(cls.tmp, "raw")
        make_synthetic_raw(cls.raw)

    @classmethod
    def tearDownClass(cls):
        if KEEP:
            for sub in ("raw", "built", "reel"):
                src = os.path.join(cls.tmp, sub)
                if os.path.isdir(src):
                    dst = os.path.join(KEEP, sub)
                    shutil.rmtree(dst, ignore_errors=True)
                    shutil.copytree(src, dst)
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def _build(self, out):
        return ar.main(["build", "--raw", self.raw, "--out", out, "--size", SIZE, "--web-size", WEB])

    def test_build_is_deterministic_and_incremental(self):
        a, b = os.path.join(self.tmp, "built"), os.path.join(self.tmp, "built_b")
        self.assertEqual(self._build(a), 0)
        self.assertEqual(self._build(b), 0)
        files = sorted(f for f in os.listdir(os.path.join(a, "staub")) if f.endswith(".ogv"))
        self.assertEqual(files, ["shot_01.ogv", "shot_01_720.ogv", "shot_02.ogv", "shot_02_720.ogv", "shot_08.ogv", "shot_08_720.ogv"])
        for f in files:
            self.assertEqual(sha1(os.path.join(a, "staub", f)), sha1(os.path.join(b, "staub", f)), f + " renders the same twice")
        for p in ("SOURCE.txt", "LICENSE.txt", "build.json"):
            self.assertTrue(os.path.exists(os.path.join(a, "staub", p)), p + " sits beside the built clips")
        before = os.path.getmtime(os.path.join(a, "staub", "shot_01.ogv"))
        self.assertEqual(self._build(a), 0)
        self.assertEqual(before, os.path.getmtime(os.path.join(a, "staub", "shot_01.ogv")), "a current clip is not rebuilt")
        spans = {int(s["n"]): s["span"][1] - s["span"][0] for s in ar.reels()["scenes"]["staub"]["shots"]}
        for n in (1, 2, 8):
            for suffix, (w, h) in (("", (320, 180)), ("_720", (160, 90))):
                info = probe(os.path.join(a, "staub", "shot_%02d%s.ogv" % (n, suffix)))
                st = info["streams"]
                self.assertEqual(len(st), 1, "video only")
                self.assertEqual(st[0]["codec_name"], "theora")
                self.assertEqual((st[0]["width"], st[0]["height"]), (w, h))
                self.assertAlmostEqual(float(info["format"]["duration"]), spans[n], delta=0.2,
                                       msg="shot %d is conformed to its span" % n)
                self.assertEqual(decode_errors(os.path.join(a, "staub", "shot_%02d%s.ogv" % (n, suffix))), "",
                                 "shot %d%s decodes cleanly" % (n, suffix))

    def test_reel_is_deterministic(self):
        a, b = os.path.join(self.tmp, "reel"), os.path.join(self.tmp, "reel_b")
        for out in (a, b):
            self.assertEqual(ar.main(["reel", "--scene", "staub", "--raw", self.raw, "--out", out, "--size", SIZE,
                                      "--web-size", WEB]), 0)
        for f in ("staub_reel.ogv", "staub_reel_720.ogv"):
            self.assertEqual(sha1(os.path.join(a, f)), sha1(os.path.join(b, f)), f + " renders the same twice")
        info = probe(os.path.join(a, "staub_reel.ogv"))
        codecs = sorted(s["codec_name"] for s in info["streams"])
        self.assertEqual(codecs, ["theora", "vorbis"])
        secs = float(ar.cut_def("staub")["seconds"])
        self.assertAlmostEqual(float(info["format"]["duration"]), secs, delta=0.5)
        self.assertEqual(decode_errors(os.path.join(a, "staub_reel.ogv")), "", "the reel decodes cleanly")


