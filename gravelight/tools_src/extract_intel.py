"""Extracts the Intel Archive table (docs/LORE.md §13) to data/intel.json, and the character dossier
pages (docs/CHARACTERS.md "Character Dossiers") to data/dossiers.json. Re-run after editing those docs."""
import json, os, re

ROOT = os.path.join(os.path.dirname(__file__), "..")

# ---- intel
lore = open(os.path.join(ROOT, "docs/LORE.md"), encoding="utf-8").read()
sec = lore[lore.index("## 13. Intel Archive"):lore.index("## 14.")]
intel = []
for line in sec.splitlines():
    m = re.match(r"\|\s*`(INT_[A-Z0-9_]+)`\s*\|\s*(.+?)\s*\|\s*(DOC|PHOTO|CYL|RADIO|TAPE)\s*\|\s*(\w+)\s*\|\s*(.+?)\s*\|\s*$", line)
    if m:
        text = m.group(5).replace("*", "")
        intel.append({"id": m.group(1), "title": m.group(2), "type": m.group(3), "map": m.group(4), "text": text})
json.dump({"_doc": "Intel Archive (generated by tools_src/extract_intel.py from docs/LORE.md section 13).",
           "intel": intel}, open(os.path.join(ROOT, "data/intel.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
print("intel:", len(intel))

# ---- dossiers
ch = open(os.path.join(ROOT, "docs/CHARACTERS.md"), encoding="utf-8").read()
ds = ch[ch.index("## Character Dossiers"):]
kinds = {1: "record", 2: "backstory", 3: "outfit", 4: "diary", 5: "quotes", 6: "backstory", 7: "outfit", 8: "diary", 9: "card", 10: "secret"}
chars = {}
for key, header in [("dutch", "### Dutch's dossier"), ("peg", "### Peg's dossier"), ("deacon", "### Deacon's dossier"), ("wren", "### Wren's dossier")]:
    start = ds.index(header) + len(header)
    nxt = ds.find("\n### ", start)
    body = ds[start:nxt if nxt != -1 else len(ds)]
    pages = []
    cur = None
    for line in body.splitlines():
        m = re.match(r"^(\d+)\.\s+\*\*(.+?)\*\*:?\s*(.*)$", line)
        if m:
            if cur:
                pages.append(cur)
            cur = {"level": int(m.group(1)), "kind": kinds[int(m.group(1))], "title": m.group(2).rstrip(":"), "text": m.group(3).strip()}
        elif cur is not None and line.strip():
            t = re.sub(r"^\s*>\s?", "", line).rstrip()
            cur["text"] = (cur["text"] + "\n" + t).strip()
    if cur:
        pages.append(cur)
    for p in pages:
        p["text"] = p["text"].replace("*", "")
    chars[key] = pages
# cumulative dossier XP to reach each level (level 1 at 0)
thresholds = [0, 3000, 8000, 15000, 25000, 38000, 55000, 75000, 100000, 130000]
json.dump({"_doc": "Character dossiers (generated by tools_src/extract_intel.py from docs/CHARACTERS.md). xp_levels[i] = dossier XP needed for level i+1.",
           "xp_levels": thresholds, "characters": chars},
          open(os.path.join(ROOT, "data/dossiers.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
print("dossiers:", {k: len(v) for k, v in chars.items()})
